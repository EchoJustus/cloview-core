;; Regenerates verify/cljd/cljd-publics.edn: the public names of every ClojureDart
;; namespace, read from a ClojureDart source checkout. The static check
;; (verify/static_check.clj, rule `cljd-coverage`) uses it to report symbols the pinned
;; ClojureDart does not define (for example `with-redefs`), so that mistake shows up
;; without a Flutter SDK.
;;
;; Run it after changing the pinned ClojureDart version in examples/*/flutter/deps.edn:
;;
;;   clojure -M verify/cljd/extract_publics.clj <clojuredart-checkout>/clj/src/cljd <sha> > verify/cljd/cljd-publics.edn
;;
;; The checkout is in the gitlibs cache after the first `clj -M:cljd ...`:
;;   ~/.gitlibs/libs/tensegritics/clojuredart/<sha>/clj/src/cljd
;;
;; Names are collected from top-level definition forms (defn, defmacro, def, defprotocol
;; and its methods, deftype/defrecord and their constructors, declare). Dependency-free.

(require '[clojure.java.io :as io] '[clojure.string :as str] '[clojure.pprint :as pp])

(def ^:private def-re
  #"(?m)^\((defn-?|defmacro|def|defonce|defprotocol|deftype|defrecord|definterface|defmulti|declare)\s+((?:\^(?:\{[^}]*\}|#/\([^)]*\)|\S+)\s+)*)([^\s\[\]\(\)\{\}\"]+)")

(defn- ns-name-of [text]
  (second (re-find #"(?m)^\(ns\s+(?:\^(?:\{[^}]*\}|\S+)\s+)?([^\s\)\"]+)" text)))

(defn- names [text]
  (let [defs (for [[_ kind _meta nm] (re-seq def-re text)] [kind nm])
        declared (for [[_ body] (re-seq #"(?m)^\(declare\s+([^\)]*)\)" text)
                       n (str/split (str/trim body) #"\s+")
                       :when (seq n)]
                   n)
        proto-methods (for [[_ block] (re-seq #"(?ms)^\(defprotocol\s+\S+(.*?)(?=^\(|\z)" text)
                            [_ m] (re-seq #"(?m)^\s+\(([^\s\[\]\(\)]+)\s*\[" block)]
                        m)
        ctors (for [[kind nm] defs :when (#{"deftype" "defrecord"} kind)
                    c (cond-> [(str "->" nm)] (= kind "defrecord") (conj (str "map->" nm)))]
                c)]
    (set (concat (map second defs) declared proto-methods ctors))))

(let [[dir sha] *command-line-args*
      res (into (sorted-map)
                (for [^java.io.File f (file-seq (io/file dir))
                      :when (and (.isFile f) (re-find #"\.clj[cd]$" (.getName f)))
                      :let [path (str/replace (str f) "\\" "/")
                            text (slurp f)
                            nsn (ns-name-of text)]
                      :when (and nsn (not (str/includes? path "/test/")) (not= nsn "cljd.compiler"))]
                  [nsn (vec (sort (names text)))]))]
  (println ";; Public names per ClojureDart namespace, generated by verify/cljd/extract_publics.clj")
  (println (str ";; from ClojureDart " (or sha "<unknown sha>") ". Do not edit by hand."))
  (pp/pprint {:clojuredart/sha sha :namespaces res}))
